#!/usr/bin/env bash
# Creates /srv/ujglobal/<stack>/.env with every secret generated, and the edge's .env with the staging
# password. You then only fill in the email settings (and BACKUP_REMOTE if you use one).
#
#   new-env.sh <production|staging>       refuses to overwrite an existing .env
#   new-env.sh edge                       prompts for the staging site's username and password
set -euo pipefail

STACK="${1:?usage: new-env.sh <production|staging|edge>}"
ROOT="${UJ_ROOT:-/srv/ujglobal}"
secret() { openssl rand -hex 32; }

if [[ "$STACK" == edge ]]; then
	file="$ROOT/edge/.env"
	read -r -p "Username for the staging site: " user
	read -r -s -p "Password for the staging site: " pass && echo
	# caddy hash-password gives the bcrypt hash Caddy's basic_auth expects.
	hash="$(docker run --rm caddy:2.8-alpine caddy hash-password --plaintext "$pass")"
	umask 077
	printf 'STAGING_USER=%s\nSTAGING_PASSWORD_HASH=%s\n' "$user" "$hash" >"$file"
	echo "Wrote $file"
	exit 0
fi

case "$STACK" in
production) site=https://ujglobal.tech api=https://api.ujglobal.tech env=production ;;
staging) site=https://staging.ujglobal.tech api=https://api-staging.ujglobal.tech env=staging ;;
*) echo "Unknown stack: $STACK" >&2; exit 2 ;;
esac

file="$ROOT/$STACK/.env"
[[ -e "$file" ]] && { echo "$file already exists; not overwriting it." >&2; exit 1; }
db_password="$(secret)"
umask 077
cat >"$file" <<ENV
# UJ Global $STACK settings, generated by new-env.sh on $(date -u +%Y-%m-%d). Never commit this file.
# Fill in the EMAIL section, then deploy. Everything else is ready.
STACK=$STACK
ENVIRONMENT=$env

# --- Database (inside this stack only) ---
POSTGRES_USER=ujglobal
POSTGRES_PASSWORD=$db_password
POSTGRES_DB=ujglobal
DATABASE_URL=postgresql+asyncpg://ujglobal:$db_password@postgres:5432/ujglobal
REDIS_URL=redis://redis:6379/0

# --- Secrets (random; the API refuses to start with defaults) ---
IP_HASH_SALT=$(secret)
JWT_SECRET=$(secret)
REVALIDATE_SECRET=$(secret)

# --- Addresses ---
CORS_ORIGINS=["$site"]
ADMIN_BASE_URL=$site
COOKIE_SECURE=true
# The STACK-prefixed name, never plain "api": both stacks share the edge network.
API_INTERNAL_URL=http://$STACK-api:8000
WEB_REVALIDATE_URL=http://web:3000/api/revalidate
# (The browser-facing API address, $api, is built into the web image.)

# --- EMAIL: fill these in (docs/DEPLOY.md, step 5) ---
# Resend:   SMTP_HOST=smtp.resend.com     SMTP_USERNAME=resend      SMTP_PASSWORD=<API key>
# Postmark: SMTP_HOST=smtp.postmarkapp.com SMTP_USERNAME=<token>    SMTP_PASSWORD=<same token>
SMTP_HOST=
SMTP_PORT=587
SMTP_USERNAME=
SMTP_PASSWORD=
SMTP_SECURITY=starttls
EMAIL_FROM=UJ Global <no-reply@ujglobal.tech>
# Who gets an email for each new lead. On staging, [] switches alerts off.
LEAD_ALERT_RECIPIENTS=$( [[ "$STACK" == production ]] && echo '["you@ujglobal.tech"]' || echo '[]' )

# --- Privacy: must match the privacy policy (24 months) ---
LEAD_RETENTION_DAYS=730
ACCESS_TOKEN_MINUTES=15
REFRESH_TOKEN_DAYS=14

# --- Optional: copy nightly backups off the server (an rclone remote, e.g. r2:ujglobal-backups) ---
BACKUP_REMOTE=
ENV
if [[ "$STACK" == production ]]; then
	echo "Wrote $file. Next: fill in the EMAIL section and LEAD_ALERT_RECIPIENTS."
else
	echo "Wrote $file. Lead alerts are off on staging; add email settings only if you want to test them."
fi
